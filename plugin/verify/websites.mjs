import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Readable } from 'node:stream';
import { initWebsites, validateSites, websiteSources, registerWebsiteRoutes } from '../src/host/websites/index.js';
import { publicAddress } from '../src/host/websites/read.js';
import { NEWS_SOURCES, pickSources } from '../src/host/sources.js';
const dir = mkdtempSync(join(tmpdir(), 'yushe-sites-'));
try {
  initWebsites(dir, NEWS_SOURCES);
  assert.equal(websiteSources().length, 6);
  assert.equal(pickSources('test').length, 3);
  assert.throws(() => validateSites([{name:'x',url:'file:///x',type:'page',enabled:true}]));
  assert.throws(() => validateSites(Array(31).fill({})));
  for (const ip of ['127.0.0.1','10.0.0.1','192.168.1.1','169.254.169.254','172.16.0.1','::1','::ffff:127.0.0.1']) assert.equal(publicAddress(ip),false);
  assert.equal(publicAddress('8.8.8.8'),true);
  let handler, result;
  registerWebsiteRoutes({scope:{effect:f=>f(), webServer:{register:r=>{handler=r.handler;}}},isLoopbackRequest:r=>r.local!==false,writeJson:(_res,status,body)=>{result={status,body};}});
  const save=async sites=>{ const req=Readable.from([Buffer.from(JSON.stringify({sites}))]); req.method='POST'; req.headers={host:'localhost'}; await handler(req,{}); return result; };
  assert.equal((await save([])).status,200);
  assert.deepEqual(pickSources('test'),[]);
  const site={name:'Example',url:'https://example.com/',kind:'网站',type:'page',enabled:true};
  assert.equal((await save([site])).body.sites.length,1);
  assert.equal(pickSources('test')[0].name,'Example');
  assert.equal((await save([{...site,enabled:false}])).status,200);
  assert.deepEqual(pickSources('test'),[]);
  assert.equal((await save([site,site])).status,400);
  assert.equal(JSON.parse(readFileSync(join(dir,'websites.json'))).sites[0].enabled,false);
  await handler({method:'GET',local:false},{}); assert.equal(result.status,403);
  console.log('Website config, persistence, routes and address checks passed');
} finally {rmSync(dir,{recursive:true,force:true});}
